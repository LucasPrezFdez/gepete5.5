// Helper: pick a game from FALLBACK_GAMES by slug. Throws if not found
// (forces you to use real slugs, no typos).
function pickGame(slug: string): Game {
  const game = FALLBACK_GAMES.find((g) => g.slug === slug);
  if (!game) throw new Error(`Mock data references unknown game slug: ${slug}`);
  return game;
}

const avatar = (seed: string) =>
  `https://api.dicebear.com/9.x/avataaars/svg?seed=${encodeURIComponent(seed)}`;

function listItems(entries: Array<[string, string | null]>): GameListItem[] {
  return entries.map(([slug, note], idx) => ({
    game: pickGame(slug),
    position: idx + 1,
    note,
  }));
}

