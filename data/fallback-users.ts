export const FALLBACK_USERS: MockUser[] = users;

export const FALLBACK_USERS_BY_USERNAME = new Map(
  FALLBACK_USERS.map((u) => [u.profile.username.toLowerCase(), u])
);

export function getFallbackReviewsByGameSlug(slug: string): Review[] {
  const normalized = slug.trim().toLowerCase();
  if (!normalized) return [];
  const result: Review[] = [];
  for (const user of FALLBACK_USERS) {
    for (const review of user.reviews) {
      if (review.gameSlug.toLowerCase() === normalized) result.push(review);
    }
  }
  return result.sort((a, b) => (b.createdAt > a.createdAt ? 1 : -1));
}

export function getFallbackListBySlug(slug: string): GameList | null {
  const normalized = slug.trim().toLowerCase();
  if (!normalized) return null;
  for (const user of FALLBACK_USERS) {
    for (const list of user.lists) {
      if (list.slug.toLowerCase() === normalized) return list;
    }
  }
  return null;
}
